@app.command("build-crew")
def build_crew(
    project_path: str,
    describe: str = typer.Option(..., help="Natural language overall project goal description")
):
    """
    Proposes entire crew orchestrations (crews, agents, and task lists) via LLM.
    """
    config_file = os.path.join(project_path, "agentos.config.yaml")
    preferred_tags = ["fast"]
    if os.path.exists(config_file):
        try:
            with open(config_file, "r", encoding="utf-8") as f:
                p_cfg = yaml.safe_load(f)
                preferred_tags = p_cfg.get("preferred_tags", ["fast"])
        except:
            pass
            
    llm_client = LLMClient(preferred_tags=preferred_tags)
    builder = CrewBuilder(llm_client=llm_client)
    
    console.print("[bold blue]Proposing Crew Orchestration design via LLM...[/bold blue]")
    try:
        proposed = builder.create_from_goal(describe)
    except Exception as e:
        console.print(f"[bold red]LLM Generation failed:[/bold red] {e}")
        raise typer.Exit(code=1)
        
    json_str = json.dumps(proposed, indent=2)
    console.print("\n[bold yellow]Proposed Crew Structure (JSON):[/bold yellow]")
    console.print(Syntax(json_str, "json", theme="monokai", line_numbers=True))
    
    confirm = typer.confirm("Do you want to write these proposed Agent, Crew, and Mission configurations to disk?")
    if confirm:
        # 1. Write agents
        for a in proposed["agents"]:
            a_cfg = {
                "name": a["name"],
                "role": a["role"],
                "goal": a["goal"],
                "backstory": a["backstory"],
                "llm_tags": ["fast"],
                "tool_refs": a.get("suggested_tools", []),
                "memory_ref": None
            }
            a_file = os.path.join(project_path, "agents", f"{a['name'].lower().replace(' ', '_')}.yaml")
            with open(a_file, "w", encoding="utf-8") as f:
                yaml.safe_dump(a_cfg, f)
            console.print(f"[green]OK[/green] Wrote Agent definition: {a_file}")
            
        # 2. Write Crew
        c_names = [a["name"] for a in proposed["agents"]]
        c_cfg = {
            "name": proposed["name"],
            "agents": c_names,
            "process": proposed.get("process", "sequential")
        }
        c_file = os.path.join(project_path, "crews", f"{proposed['name'].lower().replace(' ', '_')}.yaml")
        with open(c_file, "w", encoding="utf-8") as f:
            yaml.safe_dump(c_cfg, f)
        console.print(f"[green]OK[/green] Wrote Crew definition: {c_file}")
        
        # 3. Write Mission
        m_tasks = []
        for t in proposed["tasks"]:
            m_tasks.append({
                "description": t["description"],
                "assigned_agent": t["assigned_agent"]
            })
        m_cfg = {
            "name": f"{proposed['name']}Mission",
            "goal": describe,
            "description": f"Auto-generated mission for crew: {proposed['name']}",
            "crew": proposed["name"],
            "tasks": m_tasks
        }
        m_file = os.path.join(project_path, "missions", f"{proposed['name'].lower().replace(' ', '_')}_mission.yaml")
        with open(m_file, "w", encoding="utf-8") as f:
            yaml.safe_dump(m_cfg, f)
        console.print(f"[green]OK[/green] Wrote Mission definition: {m_file}")
        
        console.print("[bold green]Success: All proposed configs written to disk successfully.[/bold green]")
    else:
        console.print("[yellow]Cancelled configuration write.[/yellow]")


