@app.command("validate")
def validate(project_path: str):
    """
    Validates all project YAML files against Pydantic schemas without executing them.
    """
    errors = 0
    
    # 1. Validate agentos.config.yaml
    config_file = os.path.join(project_path, "agentos.config.yaml")
    if os.path.exists(config_file):
        try:
            with open(config_file, "r", encoding="utf-8") as f:
                data = yaml.safe_load(f)
            ProjectConfig(**data)
            console.print(f"[green]OK[/green] Config validated: {config_file}")
        except Exception as e:
            console.print(f"[bold red]ERROR in {config_file}:[/bold red]\n{e}")
            errors += 1
            
    # 2. Validate agents/
    agents_dir = os.path.join(project_path, "agents")
    if os.path.exists(agents_dir):
        for fpath in glob.glob(os.path.join(agents_dir, "*.yaml")):
            try:
                with open(fpath, "r", encoding="utf-8") as f:
                    data = yaml.safe_load(f)
                AgentYAMLConfig(**data)
                console.print(f"[green]OK[/green] Agent validated: {fpath}")
            except Exception as e:
                console.print(f"[bold red]ERROR in {fpath}:[/bold red]\n{e}")
                errors += 1
                
    # 3. Validate crews/
    crews_dir = os.path.join(project_path, "crews")
    if os.path.exists(crews_dir):
        for fpath in glob.glob(os.path.join(crews_dir, "*.yaml")):
            try:
                with open(fpath, "r", encoding="utf-8") as f:
                    data = yaml.safe_load(f)
                CrewYAMLConfig(**data)
                console.print(f"[green]OK[/green] Crew validated: {fpath}")
            except Exception as e:
                console.print(f"[bold red]ERROR in {fpath}:[/bold red]\n{e}")
                errors += 1
                
    # 4. Validate missions/
    missions_dir = os.path.join(project_path, "missions")
    if os.path.exists(missions_dir):
        for fpath in glob.glob(os.path.join(missions_dir, "*.yaml")):
            try:
                with open(fpath, "r", encoding="utf-8") as f:
                    data = yaml.safe_load(f)
                MissionYAMLConfig(**data)
                console.print(f"[green]OK[/green] Mission validated: {fpath}")
            except Exception as e:
                console.print(f"[bold red]ERROR in {fpath}:[/bold red]\n{e}")
                errors += 1

    if errors > 0:
        console.print(f"\n[bold red]Validation failed with {errors} errors.[/bold red]")
        raise typer.Exit(code=1)
    else:
        console.print("\n[bold green]Validation passed successfully![/bold green]")

