@app.command("new-crew")
def new_crew(
    project_path: str,
    name: str = typer.Option(..., help="Name of the crew"),
    agents: str = typer.Option(..., help="Comma-separated agent names to include"),
    process: str = typer.Option("sequential", help="Process type: sequential or hierarchical")
):
    """
    Creates a new crew YAML configuration validating agent names.
    """
    agent_names = [a.strip() for a in agents.split(",") if a.strip()]
    
    # Validate agent names exist
    agents_dir = os.path.join(project_path, "agents")
    existing_agents = []
    if os.path.exists(agents_dir):
        for file in glob.glob(os.path.join(agents_dir, "*.yaml")):
            with open(file, "r", encoding="utf-8") as f:
                try:
                    data = yaml.safe_load(f)
                    existing_agents.append(data.get("name"))
                except:
                    pass
                    
    for a in agent_names:
        if a not in existing_agents:
            console.print(f"[bold red]Error:[/bold red] Agent '{a}' is not defined in any YAML files under agents/.")
            raise typer.Exit(code=1)
            
    config = CrewYAMLConfig(name=name, agents=agent_names, process=process)
    dest_path = os.path.join(project_path, "crews", f"{name.lower().replace(' ', '_')}.yaml")
    
    with open(dest_path, "w", encoding="utf-8") as f:
        yaml.safe_dump(config.model_dump(), f)
        
    console.print(f"[bold green]Success:[/bold green] Created crew '{name}' at {dest_path}")


