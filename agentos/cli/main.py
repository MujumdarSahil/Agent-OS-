@app.command("build-agent")
def build_agent(
    project_path: str,
    describe: str = typer.Option(..., help="Natural language description of the agent")
):
    """
    Proposes agent configuration via LLM and writes to agents/ after confirmation.
    """
    config_file = os.path.join(project_path, "agentos.config.yaml")
    preferred_tags = ["fast"]
    if os.path.exists(config_file):
        try:
            with open(config_file, "r", encoding="utf-8") as f:
                p_cfg = yaml.safe_load(f)
                preferred_tags = p_cfg.get("preferred_tags", ["fast"])
        except:
            pass
            
    llm_client = LLMClient(preferred_tags=preferred_tags)
    builder = AgentBuilder(llm_client=llm_client)
    
    console.print("[bold blue]Proposing Agent configuration via LLM...[/bold blue]")
    try:
        proposed = builder.create_from_description(describe)
    except Exception as e:
        console.print(f"[bold red]LLM Generation failed:[/bold red] {e}")
        raise typer.Exit(code=1)
        
    yaml_str = yaml.safe_dump(proposed, default_flow_style=False)
    console.print("\n[bold yellow]Proposed Agent YAML:[/bold yellow]")
    console.print(Syntax(yaml_str, "yaml", theme="monokai", line_numbers=True))
    
    confirm = typer.confirm("Do you want to write this configuration to agents/?")
    if confirm:
        file_name = f"{proposed['name'].lower().replace(' ', '_')}.yaml"
        dest_path = os.path.join(project_path, "agents", file_name)
        with open(dest_path, "w", encoding="utf-8") as f:
            f.write(yaml_str)
        console.print(f"[bold green]Success:[/bold green] Wrote Agent config to {dest_path}")
    else:
        console.print("[yellow]Cancelled configuration write.[/yellow]")


