"""
Tests for JobsConfig validation and loader.
"""

from pathlib import Path
import pytest
from pydantic import ValidationError

from agentos.jobs.config import (
    JobsConfig,
    load_jobs_config,
    get_repo_root,
)


def test_default_config(tmp_path: Path):
    """Confirm default config sets safe defaults: disabled, no providers, zero budget."""
    cfg = JobsConfig(db_path=str(tmp_path / "jobs.db"))
    assert cfg.enabled is False
    assert cfg.allowed_providers == []
    assert cfg.max_llm_calls_per_run == 0
    assert cfg.sources == []
    assert cfg.notify_email_enabled is False
    assert cfg.run_timeout_seconds == 300


def test_default_db_path_is_outside_repo():
    """Default db_path generated by system must be outside repository root."""
    repo_root = get_repo_root().resolve()
    cfg = JobsConfig()
    db_path = Path(cfg.db_path).resolve()
    with pytest.raises(ValueError):
        # If relative_to fails, it means db_path is NOT inside repo_root, which is what we want!
        db_path.relative_to(repo_root)


def test_repo_path_db_rejected():
    """Confirm paths inside the repository directory are rejected."""
    repo_root = get_repo_root()
    inside_paths = [
        str(repo_root / "jobs.db"),
        str(repo_root / "agentos" / "jobs.db"),
        "./jobs.db",
        "agentos/jobs/test.db",
    ]
    for p in inside_paths:
        with pytest.raises(ValidationError) as exc_info:
            JobsConfig(db_path=p)
        assert "resolves inside the repository root" in str(exc_info.value)


def test_outside_db_path_accepted(tmp_path: Path):
    """Confirm paths strictly outside repo (like tmp_path) are accepted."""
    outside_db = str(tmp_path / "safe" / "jobs.db")
    cfg = JobsConfig(db_path=outside_db)
    assert Path(cfg.db_path).resolve() == Path(outside_db).resolve()


def test_range_validation_errors(tmp_path: Path):
    """Confirm inverted ranges trigger validation errors."""
    db = str(tmp_path / "jobs.db")
    with pytest.raises(ValidationError) as exc:
        JobsConfig(db_path=db, experience_min=5, experience_max=2)
    assert "experience_min" in str(exc.value)

    with pytest.raises(ValidationError) as exc:
        JobsConfig(db_path=db, salary_min=200000, salary_max=100000)
    assert "salary_min" in str(exc.value)


def test_load_example_config():
    """Confirm shipping jobs.config.example.yaml loads and validates cleanly."""
    example_path = Path(__file__).resolve().parent.parent.parent / "jobs" / "jobs.config.example.yaml"
    assert example_path.exists()
    cfg = load_jobs_config(example_path)
    assert cfg.enabled is False
    assert cfg.allowed_providers == []
    assert cfg.max_llm_calls_per_run == 0


def test_load_config_missing_file():
    """Missing file raises FileNotFoundError."""
    with pytest.raises(FileNotFoundError):
        load_jobs_config("non_existent_file_path_12345.yaml")


def test_load_config_invalid_yaml(tmp_path: Path):
    """Malformed YAML raises ValueError."""
    bad_file = tmp_path / "bad.yaml"
    bad_file.write_text("::: not valid yaml :::", encoding="utf-8")
    with pytest.raises(ValueError):
        load_jobs_config(bad_file)


def test_load_config_non_dict_yaml(tmp_path: Path):
    """YAML list or scalar root raises ValueError."""
    scalar_file = tmp_path / "scalar.yaml"
    scalar_file.write_text("- item1\n- item2\n", encoding="utf-8")
    with pytest.raises(ValueError):
        load_jobs_config(scalar_file)
